const DICT: Record<Lang, Dict> = { tr: TR, en: EN, es: ES, de: DE, fr: FR }

interface LangCtx {
  lang: Lang
  setLang: (l: Lang) => void
  t: (key: string, params?: Record<string, string | number>) => string
}

const Ctx = createContext<LangCtx>({ lang: 'tr', setLang: () => {}, t: (k) => k })

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      const s = localStorage.getItem('tavla.lang')
      return LANGS.some((l) => l.code === s) ? (s as Lang) : 'tr'
    } catch {
      return 'tr'
    }
  })
  const setLang = (l: Lang) => {
    setLangState(l)
    try {
      localStorage.setItem('tavla.lang', l)
    } catch {
      /* yok */
    }
  }
  useEffect(() => {
    document.documentElement.lang = lang
  }, [lang])
  const t = (key: string, params?: Record<string, string | number>) => {
    let s = DICT[lang][key] ?? DICT.en[key] ?? DICT.tr[key] ?? key
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        s = s.split(`{${k}}`).join(String(v))
      }
    }
    return s
  }
  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>
}

export function useT(): LangCtx {
  return useContext(Ctx)
}
